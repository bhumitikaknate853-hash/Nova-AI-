package com.example.data.offline

import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object OfflineKnowledgeEngine {

    data class OfflineResult(
        val text: String,
        val suggestedAction: String? = null
    )

    private val stemDatabase = mapOf(
        "speed of light" to "The speed of light in vacuum is approximately 299,792,458 meters per second (approx. 3 × 10⁸ m/s).",
        "gravity" to "Standard acceleration due to Earth's gravity (g) is approximately 9.80665 m/s².",
        "photosynthesis" to "Photosynthesis is the biological process by which green plants and certain other organisms transform light energy into chemical energy: 6CO₂ + 6H₂O + light → C₆H₁₂O₆ + 6O₂.",
        "dna" to "DNA (Deoxyribonucleic acid) is the hereditary molecule in almost all organisms, composed of two strands forming a double helix of nucleotides: Adenine (A), Thymine (T), Guanine (G), and Cytosine (C).",
        "mitochondria" to "Mitochondria are membrane-bound cell organelles that generate most of the chemical energy needed to power the cell's biochemical reactions (ATP). Often called the 'powerhouse of the cell'.",
        "pythagoras" to "The Pythagorean theorem states that in a right-angled triangle, the square of the hypotenuse is equal to the sum of the squares of the other two sides: a² + b² = c².",
        "newton first law" to "Newton's First Law (Inertia): An object at rest stays at rest, and an object in motion stays in motion with the same speed and direction, unless acted upon by an external net force.",
        "newton second law" to "Newton's Second Law: Force equals mass multiplied by acceleration (F = m × a).",
        "newton third law" to "Newton's Third Law: For every action, there is an equal and opposite reaction."
    )

    private val codingDatabase = mapOf(
        "kotlin" to "Kotlin is a modern, statically typed, cross-platform programming language developed by JetBrains. It is Google's preferred language for Android development and features null safety, coroutines, and seamless Java interoperability.",
        "coroutine" to "A coroutine is a concurrency design pattern in Kotlin to simplify asynchronous code execution. It allows suspension and resumption of execution without blocking the underlying thread.",
        "compose" to "Jetpack Compose is Android's recommended modern declarative toolkit for building native UI using Kotlin composable functions.",
        "binary search" to "Binary Search searches a sorted array by repeatedly dividing the search interval in half. Time complexity is O(log n), space complexity is O(1).",
        "quicksort" to "QuickSort is an efficient divide-and-conquer sorting algorithm with average time complexity O(n log n).",
        "git" to "Git is a distributed version control system designed to track changes in source code during software development."
    )

    fun query(rawInput: String, languageCode: String = "en"): OfflineResult {
        val input = rawInput.trim().lowercase(Locale.ROOT)

        // Date/Time queries
        if (input.contains("time") || input.contains("date") || input.contains("what day")) {
            val sdf = SimpleDateFormat("EEEE, MMMM d, yyyy 'at' hh:mm a", Locale.getDefault())
            val formatted = sdf.format(Date())
            val reply = when (languageCode) {
                "hi" -> "स्थानिक ऑफलाइन वेळ: $formatted"
                "mr" -> "स्थानिक ऑफलाइन वेळ: $formatted"
                else -> "Current local time on device: $formatted"
            }
            return OfflineResult("$reply\n\n[⚡ Generated by NOVA Offline Engine]")
        }

        // Greetings
        if (input in listOf("hello", "hi", "hey", "namaste", "halo", "greetings")) {
            val reply = when (languageCode) {
                "hi" -> "नमस्ते! मी NOVA आहे, तुमचा ऑफलाइन AI साथी. इंटरनेटशिवाय मी तुम्हाला मूलभूत विज्ञान, कोडिंग आणि फोन टूल्समध्ये मदत करू शकतो."
                "mr" -> "नमस्कार! मी NOVA आहे, तुमचा ऑफलाइन AI मित्र. मी तुमच्या उपकरणावर स्थानिक पातळीवर कार्यरत आहे."
                else -> "Hello! I am NOVA in Offline Brain Mode. Even without an active internet connection, I can assist you with STEM facts, math formulas, programming concepts, study decks, and native phone actions."
            }
            return OfflineResult("$reply\n\n[⚡ NOVA Offline Brain]")
        }

        // Phone intent detections
        if (input.contains("camera") || input.contains("photo") || input.contains("picture")) {
            return OfflineResult(
                "I can open the camera for you. Tap the Phone Tools icon or use the action below.",
                suggestedAction = "OPEN_CAMERA"
            )
        }
        if (input.contains("dial") || input.contains("call") || input.contains("phone")) {
            return OfflineResult(
                "I can open the Phone Dialer. Enter a number in Phone Tools.",
                suggestedAction = "DIAL_PHONE"
            )
        }
        if (input.contains("message") || input.contains("sms") || input.contains("text someone")) {
            return OfflineResult(
                "I can prepare a text message for you via the Messaging app.",
                suggestedAction = "SEND_SMS"
            )
        }
        if (input.contains("setting") || input.contains("wifi") || input.contains("bluetooth")) {
            return OfflineResult(
                "I can open Android System Settings for you.",
                suggestedAction = "SYSTEM_SETTINGS"
            )
        }

        // Math evaluation attempt
        val mathMatch = Regex("""([-+]?[0-9]*\.?[0-9]+)\s*([\+\-\*\/])\s*([-+]?[0-9]*\.?[0-9]+)""").find(input)
        if (mathMatch != null) {
            val (num1Str, op, num2Str) = mathMatch.destructured
            val n1 = num1Str.toDoubleOrNull()
            val n2 = num2Str.toDoubleOrNull()
            if (n1 != null && n2 != null) {
                val res = when (op) {
                    "+" -> n1 + n2
                    "-" -> n1 - n2
                    "*" -> n1 * n2
                    "/" -> if (n2 != 0.0) n1 / n2 else Double.NaN
                    else -> null
                }
                if (res != null) {
                    val cleanRes = if (res == res.toLong().toDouble()) res.toLong().toString() else "%.4f".format(res)
                    return OfflineResult("Calculation result: $n1 $op $n2 = $cleanRes\n\n[⚡ On-device Math Engine]")
                }
            }
        }

        // STEM search
        for ((term, explanation) in stemDatabase) {
            if (input.contains(term)) {
                return OfflineResult("• **Topic:** ${term.replaceFirstChar { it.uppercase() }}\n\n$explanation\n\n[⚡ Retrieved from NOVA On-Device Knowledge Bank]")
            }
        }

        // Coding search
        for ((term, explanation) in codingDatabase) {
            if (input.contains(term)) {
                return OfflineResult("• **Programming Concept:** ${term.replaceFirstChar { it.uppercase() }}\n\n$explanation\n\n[⚡ Retrieved from NOVA On-Device Knowledge Bank]")
            }
        }

        // Fallback offline guidance
        val fallback = when (languageCode) {
            "hi" -> "मी सध्या ऑफलाइन मोडमध्ये आहे. तुम्ही इंटरनेट कनेक्ट करताच मी रिअल-टाइम माहिती शोधू शकेन. तरीही तुम्ही फोन टूल्स, विज्ञान सूत्रे आणि स्टडी कार्ड्स वापरू शकता."
            "mr" -> "सध्या इंटरनेट उपलब्ध नाही (ऑफलाइन मोड). मी मूलभूत सामान्य ज्ञान, कोडिंग संकल्पना आणि फोन टूल्स हाताळू शकतो."
            else -> "I am currently in Offline Mode. Live worldwide internet queries and generative multimodal models require an internet connection.\n\nHowever, I can still help you with:\n• Built-in STEM and Physics formulas\n• Kotlin & Programming fundamentals\n• Quick arithmetic calculations\n• Native Android phone actions (Camera, Dialer, SMS, Settings)\n• Offline Study flashcards\n\nConnect to Wi-Fi/Mobile Data or configure an API key in Settings to activate full cloud capabilities."
        }
        return OfflineResult("$fallback\n\n[⚡ Offline Mode Notice]")
    }
}
